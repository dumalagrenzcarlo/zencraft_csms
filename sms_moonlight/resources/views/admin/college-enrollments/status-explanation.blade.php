<div class="enrolment-status-guide">
    <p>Status controls whether the enrolment is active and how it is used by the system.</p>
    <ul>
        <li><code>Enrolled</code> — active in the student portal and automatically assigned to matching classes.</li>
        <li><code>Pending</code> — recorded but not active; classes are not assigned until changed to Enrolled.</li>
        <li><code>Completed</code> — retained as finished academic history and no longer active.</li>
        <li><code>Withdrawn</code> — retained in history but indicates that the student left the course.</li>
    </ul>
</div>

